"""Regex patterns for GitLab content analysis.

Used by compliance checks to detect issue links, branch naming, commit refs, etc.
"""

import re
from fnmatch import fnmatch

# -- Issue link patterns in MR descriptions --
# GitLab auto-close patterns: https://docs.gitlab.com/ee/user/project/issues/managing_issues.html
ISSUE_LINK_PATTERNS = [
    re.compile(r"(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s+#(\d+)", re.IGNORECASE),
    re.compile(r"(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s+(?:\S+)#(\d+)", re.IGNORECASE),
    # Bare reference \u2014 require a word boundary before # (so "Hi #1 fan"
    # doesn't accidentally match) but allow the start of line / whitespace
    # / common punctuation. Followed by digits and a word boundary so
    # "v#10" / "#10x" don't false-match.
    re.compile(r"(?:(?<=^)|(?<=[\s(,.;:>]))#(\d+)\b"),
]


def extract_linked_issue_iids(description: str | None) -> list[int]:
    """Extract issue IIDs referenced in an MR description.

    Returns list of IIDs found, ordered by specificity (closing patterns first).
    """
    if not description:
        return []

    found: list[int] = []
    seen: set[int] = set()

    for pattern in ISSUE_LINK_PATTERNS:
        for match in pattern.finditer(description):
            iid = int(match.group(1))
            if iid not in seen:
                found.append(iid)
                seen.add(iid)

    return found


# -- Branch naming validation --


def validate_branch_name(branch_name: str, pattern: str) -> bool:
    """Validate a branch name against a regex pattern."""
    try:
        return bool(re.match(pattern, branch_name))
    except re.error:
        return False


def extract_issue_iid_from_branch(
    branch_name: str, pattern: str = r"^issue-(\d+)(-.+)?$"
) -> int | None:
    """Extract issue IID from a branch name if it matches the pattern."""
    try:
        match = re.match(pattern, branch_name)
        if match:
            return int(match.group(1))
    except (re.error, IndexError, ValueError):
        pass
    return None


# -- Commit titles GitLab wrote, not the author --
# GitLab's web IDE auto-generates commit titles matching these patterns
# when a user edits/creates/deletes a file via the browser.
_WEB_EDITOR_PATTERNS: list[re.Pattern[str]] = [
    re.compile(r"^(Update|Create|Delete|Add|Upload|Rename|Replace) \S+$", re.IGNORECASE),
    re.compile(r"^Apply \d+ suggestion", re.IGNORECASE),
]


def is_web_editor_commit(title: str | None) -> bool:
    """Return True if the commit title looks auto-generated by GitLab web editor."""
    if not title:
        return False
    return any(p.search(title) for p in _WEB_EDITOR_PATTERNS)


# -- Commit SHA references in MR comments --

COMMIT_SHA_PATTERN = re.compile(r"\b([0-9a-f]{7,40})\b")


def extract_commit_refs(text: str | None) -> list[str]:
    """Extract potential commit SHA references from text."""
    if not text:
        return []
    return COMMIT_SHA_PATTERN.findall(text)


# -- MR template compliance --


def check_template_sections(
    description: str | None, required_sections: list[str]
) -> tuple[bool, list[str]]:
    """Check if MR description contains all required template sections.

    Returns (compliant, missing_sections).
    """
    if not description:
        return False, required_sections

    missing = []
    for section in required_sections:
        if section.lower() not in description.lower():
            missing.append(section)

    return len(missing) == 0, missing


# -- Test file detection --


# Directory components that unambiguously denote a test tree. Matched as whole
# path segments (so "testimonials" / "latest" never qualify).
_TEST_DIR_NAMES = frozenset({"test", "tests", "testing", "__tests__", "spec", "specs"})


def is_test_file(file_path: str, patterns: list[str]) -> bool:
    """Check if a file path matches any of the test file glob patterns."""
    for pattern in patterns:
        if fnmatch(file_path, pattern):
            return True
    # Heuristic fallback: inspect path *segments* and the *basename*, not raw
    # substrings. Plain substring matching ("test_" in path) misclassified
    # ordinary files like "latest_data.py" / "src/testimonials/x.py" /
    # "greatest_hits.md" as tests, inflating R03.
    path_lower = file_path.lower()
    segments = path_lower.split("/")
    base = segments[-1]
    # A directory named test/tests/spec (not merely containing those letters).
    if any(seg in _TEST_DIR_NAMES for seg in segments[:-1]):
        return True
    stem = base.split(".", 1)[0]
    return (
        base.startswith("test_")
        or "_test." in base
        or ".test." in base
        or ".spec." in base
        or stem.endswith("_test")
    )


def count_test_files(file_paths: list[str], patterns: list[str]) -> int:
    """Count how many files in a list are test files."""
    return sum(1 for fp in file_paths if is_test_file(fp, patterns))


# A branch named for its issue links the MR to it, as GitLab's own "Create
# merge request" button names them: "issue-7-add-login", "7-add-login",
# "feature/issue-12".
_BRANCH_ISSUE_PATTERNS = (
    r"^issue[-_/](\d+)(?:[-_/].*)?$",
    r"^(\d+)[-_/].+$",
    r"^.+/issue[-_/](\d+)(?:[-_/].*)?$",
)


def issue_iid_from_branch(branch_name: str) -> int | None:
    """The issue a branch is named for, by any of the usual namings."""
    for pattern in _BRANCH_ISSUE_PATTERNS:
        iid = extract_issue_iid_from_branch(branch_name, pattern)
        if iid:
            return iid
    return None


def primary_linked_issue_iid(description: str | None, source_branch: str | None) -> int | None:
    """The issue an MR closes: the first one its description references,
    else the one its source branch is named for."""
    linked = extract_linked_issue_iids(description)
    if linked:
        return linked[0]
    return issue_iid_from_branch(source_branch) if source_branch else None
